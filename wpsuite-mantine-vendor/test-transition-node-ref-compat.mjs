import assert from "node:assert/strict";
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { patchTransition } from "./transition-node-ref-compat.mjs";
const here = fileURLToPath(new URL(".", import.meta.url));
const upstream = fs.readFileSync(`${here}node_modules/react-transition-group/esm/Transition.js`, "utf8");
const patched = patchTransition(upstream);
assert.equal((patched.match(/requireTransitionNodeRef\(\)/g) || []).length, 5);
assert.doesNotMatch(patched, /ReactDOM\.findDOMNode\(this\)/);
assert.throws(() => patchTransition(`${upstream}\n// changed`), /Unexpected react-transition-group/);
const notification = fs.readFileSync(`${here}node_modules/@mantine/notifications/esm/Notifications.mjs`, "utf8");
assert.equal((notification.match(/nodeRef:/g) || []).length, 1);
assert.match(notification, /nodeRef:\s*\{\s*current:\s*refs\.current\[notification\.id\]/);
const bundle = fs.readFileSync(`${here}dist/mantine-vendor.min.js`, "utf8");
assert.doesNotMatch(bundle, /findDOMNode/);
assert.match(bundle, /WP Suite transition requires nodeRef/);
const license = fs.readFileSync(`${here}node_modules/react-transition-group/LICENSE`, "utf8");
assert.equal(fs.readFileSync(`${here}dist/react-transition-group.LICENSE.txt`, "utf8"), license);
assert.ok(bundle.includes(license));
console.log("Transition patch, pinned caller, absent legacy API and BSD license: PASS");
